export const TEXTS=Object.freeze(Object.fromEntries(Object.entries(authored).map(([type,rows])=>[type,Object.freeze(rows.map((text,i)=>Object.freeze({id:`${type}-${String(i+1).padStart(2,'0')}`,text,regions:Object.freeze([...groups[i]])})))])));
// recent is part of each player's saved state. No UI-side random selection.
export function chooseText(type,region,recent,draw){
 const rows=TEXTS[type];if(!rows)throw new RangeError('Unknown numeric tile');
 let pool=rows.filter(r=>r.regions.includes(region));if(!pool.length)pool=rows;
 const fresh=pool.filter(r=>r.id!==recent[type]);if(fresh.length)pool=fresh;
 const index=draw(pool.length);if(!Number.isInteger(index)||index<0||index>=pool.length)throw Error('Invalid text draw');
 const row=pool[index];recent[type]=row.id;return row;
}

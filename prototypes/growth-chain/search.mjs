// Extract independently replayable evidence from completed fixed-seed trials.
import fs from "node:fs";
import { VERSION } from "./rules.mjs";
import { applyAction, stateData, stateHash, replay } from "./session.mjs";
import { expandAction } from "./experiments.mjs";
const dir = new URL("./results/", import.meta.url),
  list = fs
    .readdirSync(dir)
    .filter(
      (n) =>
        n.endsWith(".json") &&
        !n.includes("witness") &&
        n !== "constructed-probes.json" &&
        n !== "verification.json",
    );
const witnesses = {};
let maximum = { chain: 0 };
for (const name of list) {
  const data = JSON.parse(fs.readFileSync(new URL(name, dir)));
  if (!data.trials) continue;
  for (const trial of data.trials) {
    if (trial.maxChain > maximum.chain)
      maximum = { chain: trial.maxChain, file: name, trial };
  }
}
for (const n of [3, 5]) {
  const file = `base-6x12-5-strategic-witness-${n}.json`,
    record = JSON.parse(fs.readFileSync(new URL(file, dir)));
  let s = record.initial;
  for (const a of record.actions.slice(0, -1)) s = applyAction(s, a, false);
  const a = record.actions.at(-1),
    z = applyAction(s, a);
  if (z.last.waves.length !== n || stateHash(z) !== record.hash)
    throw Error("Witness mismatch");
  witnesses[n] = {
    state: stateData(s),
    action: a,
    chain: n,
    origin: "legal ordinary play",
    seed: s.seed,
    drop: s.drops + 1,
    source: file,
  };
  fs.writeFileSync(
    new URL(`natural-${n}-board.json`, dir),
    JSON.stringify({ ...witnesses[n], waves: z.last.waves }, null, 2),
  );
}
let s = maximum.trial.initial,
  history = [];
for (const compact of maximum.trial.actions) {
  const a = expandAction(compact);
  history.push(a);
  s = applyAction(s, a);
  if (s.last.waves.length === maximum.chain) {
    fs.writeFileSync(
      new URL("maximum-chain-witness.json", dir),
      JSON.stringify(
        {
          version: VERSION,
          initial: maximum.trial.initial,
          actions: history,
          hash: stateHash(s),
          source: maximum.file,
          chain: maximum.chain,
        },
        null,
        2,
      ),
    );
    break;
  }
}
fs.writeFileSync(
  new URL("./natural-fixtures.mjs", import.meta.url),
  "// Generated by search.mjs from verified legal histories. Do not edit.\nexport const naturalFixtures = " +
    JSON.stringify(witnesses, null, 2) +
    ";\n",
);
console.log(
  JSON.stringify({
    natural: Object.values(witnesses).map((w) => ({
      chain: w.chain,
      seed: w.seed,
      drop: w.drop,
    })),
    maximum: maximum.chain,
    source: maximum.file,
  }),
);

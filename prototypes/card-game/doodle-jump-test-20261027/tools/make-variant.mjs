// EXPERIMENT ONLY. Generates isolated copies of the card-game runtime for the ぴょんぴょんジャンプ comparison.
//   .variant-B/    : improvement B — "next time-skip: draw 1; if that time-skip raised exactly one stage, also +5"
//   .variant-null/ : the same copied module set with NO patch, used to prove that copying alone changes nothing
// Only the modules that (transitively) import a patched module are copied; every other import points back to the
// official file. Official sources are read, never written. Generated directories are gitignored, not in
// tools/pages/allowlist.json and not imported by any runtime file.  Usage: node tools/make-variant.mjs
import {readFileSync,writeFileSync,mkdirSync,readdirSync} from 'node:fs';import {createHash} from 'node:crypto';
import {dirname,join} from 'node:path';import {fileURLToPath} from 'node:url';
const here=dirname(fileURLToPath(import.meta.url)),game=join(here,'..','..'),root=join(here,'..');
const sha=t=>createHash('sha256').update(t).digest('hex');
// Each patch must match exactly once in the official source.
const PATCHES={
 'remaining-rules.mjs':[[
  "'G-doodle-jump':quick([reserve('time_skip',[],{sequence:[[draw()],[growth(5)]]})]),",
  "'G-doodle-jump':quick([reserve('time_skip',[draw(),iff('singleStageTimeSkip',[growth(5)])])]),"]],
 'late-conditions.mjs':[[
  " switch(key){",
  " switch(key){\n case 'singleStageTimeSkip':return ev.kind==='time_skip'&&(card(s,ev.source)?.stage??0)-(card(s,ev.previousMain)?.stage??99)===1;"]],
};
const mods=readdirSync(game).filter(f=>f.endsWith('.mjs'));
const imports=Object.fromEntries(mods.map(f=>[f,[...readFileSync(join(game,f),'utf8').matchAll(/from '\.\/([\w-]+\.mjs)'/g)].map(m=>m[1])]));
// Closure: patched modules plus everything that imports them, directly or indirectly.
const copy=new Set(Object.keys(PATCHES));let grew=true;
while(grew){grew=false;for(const f of mods)if(!copy.has(f)&&imports[f].some(i=>copy.has(i))){copy.add(f);grew=true;}}
// UI modules are never part of a match run; keep them out of the copy so nothing UI-related is duplicated.
const RUN=['engine.mjs','cpu-observation.mjs','auto-progress.mjs'];
const needed=new Set();const walk=f=>{if(needed.has(f)||!copy.has(f))return;needed.add(f);imports[f].forEach(walk);};RUN.forEach(walk);
for(const f of RUN)needed.add(f);
const report={sources:{},variants:{}};
for(const variant of ['B','null']){
 const out=join(root,'.variant-'+variant);mkdirSync(out,{recursive:true});report.variants[variant]={};
 for(const f of [...needed].sort()){
  let t=readFileSync(join(game,f),'utf8');report.sources[f]=sha(t);
  if(variant==='B')for(const [from,to] of PATCHES[f]??[]){const n=t.split(from).length-1;if(n!==1)throw Error(`${f}: patch matched ${n} times`);t=t.replace(from,()=>to);}
  t=t.replace(/from '\.\/([\w-]+\.mjs)'/g,(m,x)=>needed.has(x)?m:`from '../../${x}'`);
  t=`// GENERATED BY doodle-jump-test-20261027/tools/make-variant.mjs (variant ${variant}) — EXPERIMENT ONLY. Do not import from runtime.\n`+t;
  writeFileSync(join(out,f),t);report.variants[variant][f]=sha(t);
 }
 writeFileSync(join(out,'package.json'),'{"type":"module"}\n');
}
report.copied=[...needed].sort();
console.log(JSON.stringify(report,null,1));

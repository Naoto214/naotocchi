"""Pin the normative rules verbatim; no older proposal or test-deck counts."""
import json,pathlib,hashlib
root=pathlib.Path(__file__).resolve().parents[2]
rows=[]
for name,end in [('01-core-rules.md',None),('02-main-system.md',None),('06-action-chain-checkpoint.md',None),('07-advanced-rules-checkpoint.md','# 第0弾テストデッキA')]:
    raw=(root/'docs/card-game'/name).read_text()
    text=raw.split(end)[0] if end else raw
    rows.append(dict(path=name,endMarker=end,text=text,sha256=hashlib.sha256(text.encode()).hexdigest()))
(root/'prototypes/card-game/rulebook-sources.mjs').write_text('// Generated by build-rulebook-sources.py from the approved normative documents.\nexport const SOURCES = '+json.dumps(rows,ensure_ascii=False,indent=2)+';\n')

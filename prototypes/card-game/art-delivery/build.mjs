// Reproducible delivery assets from the byte-preserved PR #393 manifest/originals.
// NODE_PATH may point at the host runtime's sharp installation.
import {createRequire} from 'node:module';
import {readFile,writeFile,mkdir} from 'node:fs/promises';
import {createHash} from 'node:crypto';
import {fileURLToPath} from 'node:url';
import {CATALOG} from '../full-catalog.mjs';
const require=createRequire(import.meta.url),sharp=require('sharp');
const base=new URL('../art-pilot/',import.meta.url),out=new URL('./',import.meta.url);
const sourceManifest=new URL('rollout/final-452-20261019/deck-manifest.json',base);
const manifest=JSON.parse(await readFile(sourceManifest,'utf8'));
const sha=b=>createHash('sha256').update(b).digest('hex');
const ids=new Set(),hashes=new Set(),records=[];
for(const size of ['small','large'])await mkdir(new URL(size+'/',out),{recursive:true});
for(const card of manifest.cards){
 if(!CATALOG[card.id]||ids.has(card.id))throw Error('Invalid/duplicate ID '+card.id);
 ids.add(card.id);const original=await readFile(new URL(card.illustration,base)),hash=sha(original);
 if(hash!==card.sha256||hashes.has(hash))throw Error('Original hash mismatch/duplicate '+card.id);
 hashes.add(hash);const meta=await sharp(original).metadata();
 if(meta.width!==1536||meta.height!==1024||meta.format!=='png')throw Error('Unexpected original '+card.id);
 const r={id:card.id,source:card.illustration,source_sha256:hash,original_bytes:original.length};
 for(const [size,width,quality] of [['small',384,86],['large',1152,90]]){
  const buffer=await sharp(original).resize({width,withoutEnlargement:true}).webp({quality,effort:5}).toBuffer();
  const file=`${size}/${card.id}-${sha(buffer).slice(0,12)}.webp`;
  await writeFile(new URL(file,out),buffer);r[size]={path:`art-delivery/${file}`,width,height:width*2/3,bytes:buffer.length,sha256:sha(buffer)};
 }
 records.push(r);if(records.length%50===0)console.log('Optimized',records.length,'/452');
}
if(ids.size!==452||Object.keys(CATALOG).some(id=>!ids.has(id)))throw Error('Coverage mismatch');
const result={source_head:'a6ad1a9689335f0379d5c6795d1da8652f02ac0d',source_manifest:'art-pilot/rollout/final-452-20261019/deck-manifest.json',count:records.length,profiles:{small:{width:384,height:256,quality:86},large:{width:1152,height:768,quality:90}},totals:Object.fromEntries(['original','small','large'].map(k=>[k,records.reduce((n,r)=>n+(k==='original'?r.original_bytes:r[k].bytes),0)])),cards:records};
await writeFile(new URL('manifest.json',out),JSON.stringify(result,null,2)+'\n');
await writeFile(new URL('../ui-art.mjs',out),'// Generated by art-delivery/build.mjs from PR #393 deck-manifest.json.\n// Catalog URLs only; no state, private identities or preloading.\nexport const CARD_ART = Object.freeze('+JSON.stringify(Object.fromEntries(records.map(r=>[r.id,{small:r.small.path,large:r.large.path}])),null,2)+');\n');
console.log(JSON.stringify({count:result.count,totals:result.totals}));

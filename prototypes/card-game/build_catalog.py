"""Export only approved 114 IDs and their current canonical sections, read-only."""
import hashlib,json,re
from pathlib import Path
ROOT=Path(__file__).resolve().parents[2];DOC=ROOT/'docs/card-game'
ids=['M-beetle-01','M-antlion-01','C-box','C-cat_friend','C-chameleon','P-cliff_goat','W-deepsea','I-c_coin2','I-sleepboost1','I-bowtie','G-hit-blow','G-animal-shogi','G-archery-3d','G-area-claim','E-first-date']
names=['カブトムシ①','ウスバカゲロウ①','ただのはこ','きまぐれなねこ','サングラスのカメレオン','がけのヤギさん','しんかい','ラッキーコイン','ふかふかまくら','おべんとうばこ','ヒット&ブロー','どうぶつしょうぎ','アーチェリー','じんとり','はじめてのデート']
table=json.loads((DOC/'data/proxy-normal-decision-candidate-table-114-20260918.json').read_text())
rows={c['card_id']:c for c in table['cards']};out={}
for id,name in zip(ids,names):
 row=rows[id];ref=row['actions'][0]['source_text_reference'];file,anchor=ref.split('#');raw=(DOC/file).read_bytes();text=raw.decode();m=re.search(r'^#{2,3} '+re.escape(anchor)+r'(?:\s|$).*?(?=^#{2,3} |\Z)',text,re.M|re.S);assert m,ref
 body=m.group();effect='\n'.join(re.findall(r'^> (.*)$',body,re.M))
 if not effect:effect=re.search(r'- 本文：`(.*?)`',body).group(1)
 cost=row['actions'][0]['base_time_cost'];cost=1 if cost=='stage_or_positive_stage_difference' else cost
 out[id]=dict(id=id,name=name,type=row['card_type'],cost=cost,rare=id in ['C-box','C-chameleon'],text=effect,source=ref,source_sha256=hashlib.sha256(raw).hexdigest())
 if row['card_type']=='main':out[id].update(stage=1,species=id.rsplit('-',1)[0],power=2,wisdom=2 if id=='M-beetle-01' else 3)
assert len(out)==15
(Path(__file__).parent/'cards.mjs').write_text('// Generated by build_catalog.py from canonical card text.\nexport const CARDS = '+json.dumps(out,ensure_ascii=False,indent=2)+';\n')

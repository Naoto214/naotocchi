"""Approved runtime export and isolated native-AAC candidate preview."""
import json,pathlib,shutil,hashlib

def write_changed(p,text,check=False):
 if check:
  if not p.exists() or p.read_text()!=text:raise ValueError("generated export differs: "+str(p))
  return
 p.parent.mkdir(parents=True,exist_ok=True)
 if not p.exists() or p.read_text()!=text:p.write_text(text)
def build(L,data,check=False):
 from library import atomic,sha,read_json
 tracks=[t for t in data['tracks'] if t['status']=='approved'];ids={t['id'] for t in tracks}
 rows=read_json(L.music/'placements.json');extensions=read_json(L.music/'extensions.json');rows=rows+extensions['rows'];seen=set()
 for r in rows:
  if not isinstance(r.get('rowId'),str) or r['rowId'] in seen:raise ValueError('duplicate/invalid placement row')
  seen.add(r['rowId'])
  if not isinstance(r.get('songs'),list) or not set(r['songs'])<=ids:raise ValueError('placement references unapproved track')
 games=read_json(L.music/'game-songs.json');extra=extensions['gameSongs']
 if set(games)&set(extra):raise ValueError('extension cannot override existing game song')
 games={**games,**extra}
 if not all(isinstance(k,str) and k and v in ids for k,v in games.items()):raise ValueError('game placement references unapproved track')
 cat={t['id']:{'title':t['title'],'loop':t['loop']['enabled'],'duration':t['duration'],'loopStart':t['loop']['start'],'loopEnd':t['loop']['end'],'file':t['id']+'.m4a?v='+t['assets']['aac']['sha256'][:12],'sha256':t['assets']['aac']['sha256']} for t in tracks}
 files=['assets/bgm/catalog.js','assets/bgm/placement.js']+[t['assets']['aac']['path'] for t in tracks]
 write_changed(L.root/files[0],'// Generated by tools/music/library.py build; approved records only.\n(function(root){root.NAOTOCCHI_BGM_CATALOG = '+json.dumps(cat,ensure_ascii=False,indent=1)+ ';})(globalThis);\n',check)
 write_changed(L.root/files[1],'// Generated approved placements; original50 rows are protected in music/placements.json.\n(function(root){root.NAOTOCCHI_BGM_PLACEMENT = '+json.dumps({'ROWS':rows,'GAME_SONG':games},ensure_ascii=False,separators=(',',':'))+ ';})(globalThis);\n',check)
 result={'approvedIds':[t['id'] for t in tracks],'runtimeFiles':files,'sha256':{p:sha(L.root/p) for p in files}}
 if check:
  if read_json(L.music/'runtime-files.json')!=result:raise ValueError('generated runtime manifest differs')
 else:atomic(L.music/'runtime-files.json',result)
 return result

def preview(L,data,out):
 from library import atomic,sha
 out=out.resolve()
 if out==L.root or out in L.root.parents or any(out==L.root/p or L.root/p in out.parents for p in ['assets','music','prototypes']):raise ValueError('preview must be isolated from production paths')
 marker=out/'.music-preview.json'
 if out.exists() and any(out.iterdir()) and not marker.exists():raise ValueError('preview output is not an owned music preview')
 out.mkdir(parents=True,exist_ok=True);rows=[]
 for t in data['tracks']:
  src=L.root/t['assets']['aac']['path'];dst=out/'audio'/(t['id']+'.m4a');dst.parent.mkdir(exist_ok=True)
  if not dst.exists() or sha(dst)!=t['assets']['aac']['sha256']:shutil.copyfile(src,dst)
  rows.append({'id':t['id'],'title':t['title'],'status':t['status'],'file':'audio/'+t['id']+'.m4a','sha256':t['assets']['aac']['sha256']})
 atomic(out/'tracks.json',rows)
 write_changed(out/'index.html','''<!doctype html><html lang="ja"><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1"><title>なおとっち 楽曲候補比較</title><style>body{font:17px system-ui;max-width:700px;margin:2rem auto;padding:0 1rem;background:#faf8f2;color:#263a36}select,button{font:inherit;padding:.7rem;max-width:100%;margin:.3rem}audio{width:100%}</style><h1>楽曲候補比較</h1><p>候補を選び、同じ位置で切り替えて比較できます。</p><label>A<select id="a"></select></label><label>B<select id="b"></select></label><p><button id="playA">Aを再生</button><button id="playB">Bを再生</button></p><audio id="audio" controls playsinline preload="metadata"></audio><p id="status" role="status"></p><script src="player.js"></script></html>''')
 write_changed(out/'player.js','''const $=id=>document.getElementById(id),audio=$('audio');let revision=0;
fetch('tracks.json').then(r=>r.json()).then(rows=>{for(const id of ['a','b'])for(const r of rows){const o=document.createElement('option');o.value=r.file;o.textContent=r.title+' — '+r.status;$(id).append(o)}$('b').selectedIndex=Math.min(1,rows.length-1)});
function choose(id){const token=++revision,pos=audio.currentTime||0;try{if(navigator.audioSession)navigator.audioSession.type='playback'}catch(e){}audio.pause();audio.src=$(id).value;audio.onloadedmetadata=()=>{if(token!==revision)return;audio.currentTime=Math.min(pos,Math.max(0,audio.duration-.01))};audio.play().then(()=>{$('status').textContent=id.toUpperCase()+' 再生中'}).catch(e=>{$('status').textContent='再生ボタンで開始してください: '+e.message})}
$('playA').onclick=()=>choose('a');$('playB').onclick=()=>choose('b');
''')
 result={'ids':[t['id'] for t in data['tracks']],'production':False,'audioUntouched':True};atomic(marker,result);return result
